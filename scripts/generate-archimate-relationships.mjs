#!/usr/bin/env node
/**
 * Regenerates apps/server/src/generators/archimate/relationships.generated.ts from the
 * ArchiMate 3.2 relationship table published by the Archi project (MIT licence):
 *   https://github.com/archimatetool/archi/blob/master/com.archimatetool.model/model/relationships.xml
 *
 * Usage: node scripts/generate-archimate-relationships.mjs <path/to/relationships.xml>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/generate-archimate-relationships.mjs <relationships.xml>');
  process.exit(1);
}

const xml = readFileSync(input, 'utf8');
const version = /<relationships version="([^"]+)"/.exec(xml)?.[1] ?? 'unknown';
const table = {};
const sourceRe = /<source concept="([A-Za-z]+)">([\s\S]*?)<\/source>/g;
const targetRe = /<target concept="([A-Za-z]+)" relations="([a-z]*)"/g;

for (const [, source, body] of xml.matchAll(sourceRe)) {
  if (source === 'Relationship') continue; // relationship-to-relationship connections are not generated by SOLAR
  const targets = {};
  for (const [, target, relations] of body.matchAll(targetRe)) {
    if (target === 'Relationship') continue;
    targets[target] = relations;
  }
  table[source] = targets;
}

const sources = Object.keys(table).sort();
const lines = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by scripts/generate-archimate-relationships.mjs - do not edit by hand.',
  `// Source: Archi relationships.xml (ArchiMate ${version}), Copyright (c) 2013-2026 Phillip Beauvoir,`,
  '// Jean-Baptiste Sarrodie, The Open Group. Licensed under the MIT License (see THIRD_PARTY_NOTICES.md).',
  '//',
  '// Key letters: a=Access c=Composition f=Flow g=Aggregation i=Assignment n=Influence',
  '//              o=Association r=Realization s=Specialization t=Triggering v=Serving',
  '',
  `export const ARCHIMATE_RELATIONSHIP_TABLE_VERSION = '${version}';`,
  '',
  'export const ARCHIMATE_RELATIONSHIP_TABLE: Readonly<Record<string, Readonly<Record<string, string>>>> = {',
];
for (const source of sources) {
  lines.push(`  ${source}: {`);
  for (const target of Object.keys(table[source]).sort()) {
    lines.push(`    ${target}: '${table[source][target]}',`);
  }
  lines.push('  },');
}
lines.push('};', '');

const out = resolve(here, '../apps/server/src/generators/archimate/relationships.generated.ts');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${sources.length} source concepts (ArchiMate ${version}) to ${out}`);
